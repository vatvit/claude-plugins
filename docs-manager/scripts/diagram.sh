#!/bin/bash
# diagram.sh — diagram sources rendered into docs. Sourced by docs.sh.
#
# A diagram source is `<name>.diagram.md`: YAML frontmatter plus exactly one fenced
# code block. A doc opts in by carrying a marker naming the source:
#
#   <!-- DIAGRAM:auth-flow.diagram.md -->
#   <!-- AUTO-DIAGRAM:START -->
#   ...generated...
#   <!-- AUTO-DIAGRAM:END -->
#
# The marker is the single declaration of the link and carries position with it.
# The fence is copied verbatim and never parsed: rendering is the viewer's job, so
# this tool needs no renderer and no dependency of any kind.

DSTART="<!-- AUTO-DIAGRAM:START — generated by scripts/docs.sh; edit the .diagram.md source, not this block -->"
DEND="<!-- AUTO-DIAGRAM:END -->"

# extract_fence <source>
#
# Print the source's fenced block verbatim, fences included. Errors (naming the
# file) on zero fences, more than one, or a missing language tag.
extract_fence() {
  local src="$1" count
  count="$(awk '/^```/ { n++ } END { print n + 0 }' "$src")"
  if [ "$count" -lt 2 ]; then
    echo "ERROR: $src — no fenced block (a diagram source needs exactly one)" >&2
    return 1
  fi
  if [ "$count" -gt 2 ]; then
    echo "ERROR: $src — $((count / 2)) fenced blocks (a diagram source needs exactly one)" >&2
    return 1
  fi
  if ! awk '/^```/ { print; exit }' "$src" | grep -qE '^```[A-Za-z0-9_-]+$'; then
    echo "ERROR: $src — fenced block has no language tag (e.g. \`\`\`mermaid)" >&2
    return 1
  fi
  awk '/^```/ { inside = !inside; print; next } inside { print }' "$src"
}

# build_diagram_block <source>
#
# The generated block, markers included. PLUG-003 appends the References line and
# PLUG-004 the staleness notice; both hook in after the fence, which is why the
# fence is emitted through a variable rather than inline.
build_diagram_block() {
  local src="$1" fence
  fence="$(extract_fence "$src")" || return 1
  printf '%s\n' "$DSTART"
  printf '%s\n' "$fence"
  printf '%s\n' "$DEND"
}

# doc_marker_source <doc> -> the source filename named by the doc's DIAGRAM marker
doc_marker_source() {
  grep -o '<!-- *DIAGRAM:[^ ]* *-->' "$1" 2>/dev/null \
    | head -1 | sed 's/.*DIAGRAM://; s/ *-->$//'
}

# cmd_diagram_index [--write|--check] [root]
cmd_diagram_index() {
  local mode="--write" root="" a
  for a in "$@"; do
    case "$a" in --write|--check) mode="$a" ;; *) root="$a" ;; esac
  done
  root="${root:-$ROOT_DEFAULT}"
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }

  local rc=0 doc name src base tmp blockfile
  blockfile="$(mktemp)"

  while IFS= read -r doc; do
    [ -n "$doc" ] || continue
    name="$(doc_marker_source "$doc")"
    [ -n "$name" ] || continue

    base="$(dirname "$doc")"
    src="$(normalize_path "$base/$name")"
    if [ ! -f "$src" ]; then
      echo "MISSING SOURCE: $doc -> $name"
      rc=1
      continue            # leave any existing block untouched
    fi

    if ! build_diagram_block "$src" > "$blockfile"; then
      rc=1
      continue            # malformed source; existing block left alone
    fi

    tmp="$(mktemp)"
    if has_marker "$doc" "$DSTART"; then
      block_rewrite "$doc" "$DSTART" "$DEND" "$blockfile" > "$tmp"
    else
      # First generation: splice the block in directly after the DIAGRAM marker.
      awk -v bf="$blockfile" '
        { print }
        /<!-- *DIAGRAM:/ && !done {
          while ((getline line < bf) > 0) print line
          close(bf); done = 1
        }
      ' "$doc" > "$tmp"
    fi

    if [ "$mode" = "--check" ]; then
      diff -q "$doc" "$tmp" >/dev/null 2>&1 \
        || { echo "DRIFT: $doc (run: scripts/docs.sh diagram index --write)"; rc=1; }
      rm -f "$tmp"
    else
      write_if_changed "$tmp" "$doc" "UPDATED" >/dev/null && echo "UPDATED: $doc"
    fi
  done <<EOF
$(find "$root" -type f -name '*.md' ! -name '*.diagram.md' | sort)
EOF

  rm -f "$blockfile"
  return $rc
}
