#!/bin/bash
# docs.sh — documentation maintenance helpers (no language runtime; pure shell + awk).
#
# Subcommands:
#   index  [--write|--check] [root]   Regenerate (or verify) the AUTO-INDEX block in each _index.md
#   links  [root]                     Report broken relative markdown links
#   check  [root]                     Run index --check + links; non-zero exit on any issue
#
# Default root is "docs". Conventions assumed:
#   - Every doc and _index.md starts with YAML frontmatter containing `title:` and `description:`.
#   - Each folder/sub-folder has an _index.md.
#   - The generated listing lives between AUTO-INDEX markers; prose outside them is preserved.
set -euo pipefail

ROOT_DEFAULT="docs"
START="<!-- AUTO-INDEX:START — generated by scripts/docs.sh; edit docs, not this block -->"
END="<!-- AUTO-INDEX:END -->"

# Extract a frontmatter scalar field (first match) from a markdown file. Empty if absent.
fm_field() {
  awk -v field="$2" '
    NR==1 && $0!="---" { exit }
    NR==1 { infm=1; next }
    infm && $0=="---" { exit }
    infm {
      key=field":"
      if (substr($0,1,length(key))==key) {
        val=substr($0,length(key)+1)
        gsub(/^[ \t]+|[ \t]+$/, "", val)
        gsub(/^"|"$/, "", val)
        print val; exit
      }
    }
  ' "$1"
}

# Lexically normalize a path (collapse . and ..). No filesystem access.
normalize_path() {
  awk -v p="$1" 'BEGIN{
    n=split(p, parts, "/"); top=0
    for(i=1;i<=n;i++){ s=parts[i]
      if(s=="."||s=="") continue
      if(s==".."){ if(top>0 && stack[top]!="..") top--; else { top++; stack[top]=s } }
      else { top++; stack[top]=s } }
    out=(substr(p,1,1)=="/")?"/":""
    for(i=1;i<=top;i++){ out=out stack[i]; if(i<top) out=out "/" }
    print out }'
}

list_subdirs() { find "$1" -mindepth 1 -maxdepth 1 -type d | sort; }
list_docs()    { find "$1" -mindepth 1 -maxdepth 1 -type f -name '*.md' ! -name '_index.md' | sort; }

# Print the AUTO-INDEX block (markers included) for a directory to stdout.
build_block() {
  local dir="$1" sub doc desc name
  printf '%s\n' "$START"
  printf '\n### Sub-folders\n'
  if [ -z "$(list_subdirs "$dir")" ]; then
    printf -- '- _(none)_\n'
  else
    while IFS= read -r sub; do
      name="$(basename "$sub")"; desc=""
      [ -f "$sub/_index.md" ] && desc="$(fm_field "$sub/_index.md" description)"
      printf -- '- [`%s/`](%s/_index.md) — %s\n' "$name" "$name" "${desc:-_(no description)_}"
    done <<EOF
$(list_subdirs "$dir")
EOF
  fi
  printf '\n### Documents\n'
  if [ -z "$(list_docs "$dir")" ]; then
    printf -- '- _(none)_\n'
  else
    while IFS= read -r doc; do
      name="$(basename "$doc")"; desc="$(fm_field "$doc" description)"
      printf -- '- [`%s`](%s) — %s\n' "$name" "$name" "${desc:-_(no description)_}"
    done <<EOF
$(list_docs "$dir")
EOF
  fi
  printf '%s\n' "$END"
}

cmd_index() {
  local mode="--write" root=""
  for a in "$@"; do
    case "$a" in --write|--check) mode="$a" ;; *) root="$a" ;; esac
  done
  root="${root:-$ROOT_DEFAULT}"
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }

  local rc=0 dir idx tmp blockfile
  blockfile="$(mktemp)"
  # Deepest-first so a parent _index.md can read freshly-written child descriptions in one pass.
  while IFS= read -r dir; do
    idx="$dir/_index.md"
    build_block "$dir" > "$blockfile"
    if [ ! -f "$idx" ]; then
      if [ "$mode" = "--check" ]; then echo "MISSING: $idx"; rc=1; continue; fi
      { printf -- '---\ntitle: %s\ndescription: TODO\n---\n\n# %s\n\n' "$(basename "$dir")" "$(basename "$dir")"; cat "$blockfile"; } > "$idx"
      echo "CREATED: $idx"; continue
    fi
    tmp="$(mktemp)"
    awk -v start="$START" -v end="$END" -v bf="$blockfile" '
      $0==start { while ((getline line < bf) > 0) print line; close(bf); skipping=1; next }
      $0==end   { skipping=0; next }
      !skipping { print }
    ' "$idx" > "$tmp"
    if ! grep -qF "$START" "$idx"; then
      printf '\n' >> "$tmp"; cat "$blockfile" >> "$tmp"
    fi
    if [ "$mode" = "--check" ]; then
      diff -q "$idx" "$tmp" >/dev/null 2>&1 || { echo "DRIFT: $idx (run: scripts/docs.sh index --write)"; rc=1; }
      rm -f "$tmp"
    else
      if diff -q "$idx" "$tmp" >/dev/null 2>&1; then rm -f "$tmp"; else mv "$tmp" "$idx"; echo "UPDATED: $idx"; fi
    fi
  done <<EOF
$(find "$root" -type d | sort -r)
EOF
  rm -f "$blockfile"
  return $rc
}

cmd_links() {
  local root="${1:-$ROOT_DEFAULT}" found=0 file link target base
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }
  while IFS= read -r file; do
    base="$(dirname "$file")"
    while IFS= read -r link; do
      case "$link" in http://*|https://*|mailto:*|\#*|"") continue ;; esac
      link="${link%%#*}"; link="${link%%\?*}"
      [ -z "$link" ] && continue
      case "$link" in /*) target="$link" ;; *) target="$(normalize_path "$base/$link")" ;; esac
      [ -e "$target" ] || { echo "BROKEN LINK: $file -> $link"; found=1; }
    done <<EOF
$(grep -oE '\]\([^)]+\)' "$file" 2>/dev/null | sed -E 's/^\]\(//; s/\)$//')
EOF
  done <<EOF
$(find "$root" -type f -name '*.md' | sort)
EOF
  return $found
}

cmd_check() {
  local root="${1:-$ROOT_DEFAULT}" rc=0
  cmd_index --check "$root" || rc=1
  cmd_links "$root" || rc=1
  [ "$rc" -eq 0 ] && echo "docs check: OK"
  return $rc
}

sub="${1:-check}"; shift || true
case "$sub" in
  index)  cmd_index "$@" ;;
  links)  cmd_links "$@" ;;
  check)  cmd_check "$@" ;;
  *) echo "Usage: docs.sh {index [--write|--check]|links|check} [root]" >&2; exit 2 ;;
esac
