#!/bin/bash
# docs.sh — documentation maintenance helpers (no language runtime; pure shell + awk).
#
# Subcommands:
#   index  [--write|--check] [root]   Regenerate (or verify) the AUTO-INDEX block in each _index.md
#   links  [root]                     Report broken relative markdown links
#   check  [root]                     Run index --check + links; non-zero exit on any issue
#
# Default root is "docs". Conventions assumed:
#   - Every doc and _index.md starts with YAML frontmatter containing `title:` and `description:`.
#   - Each folder/sub-folder has an _index.md.
#   - The generated listing lives between AUTO-INDEX markers; prose outside them is preserved.
set -euo pipefail

ROOT_DEFAULT="docs"
START="<!-- AUTO-INDEX:START — generated by scripts/docs.sh; edit docs, not this block -->"
END="<!-- AUTO-INDEX:END -->"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$SCRIPT_DIR/lib.sh"
# shellcheck source=diagram.sh
. "$SCRIPT_DIR/diagram.sh"

list_subdirs() { find "$1" -mindepth 1 -maxdepth 1 -type d | sort; }
# diagram sources are not documents — they are the input to a generated block
list_docs()    { find "$1" -mindepth 1 -maxdepth 1 -type f -name '*.md' ! -name '_index.md' ! -name '*.diagram.md' | sort; }

# Print the AUTO-INDEX block (markers included) for a directory to stdout.
build_block() {
  local dir="$1" sub doc desc name
  printf '%s\n' "$START"
  printf '\n### Sub-folders\n'
  if [ -z "$(list_subdirs "$dir")" ]; then
    printf -- '- _(none)_\n'
  else
    while IFS= read -r sub; do
      name="$(basename "$sub")"; desc=""
      [ -f "$sub/_index.md" ] && desc="$(fm_field "$sub/_index.md" description)"
      printf -- '- [`%s/`](%s/_index.md) — %s\n' "$name" "$name" "${desc:-_(no description)_}"
    done <<EOF
$(list_subdirs "$dir")
EOF
  fi
  printf '\n### Documents\n'
  if [ -z "$(list_docs "$dir")" ]; then
    printf -- '- _(none)_\n'
  else
    while IFS= read -r doc; do
      name="$(basename "$doc")"; desc="$(fm_field "$doc" description)"
      printf -- '- [`%s`](%s) — %s\n' "$name" "$name" "${desc:-_(no description)_}"
    done <<EOF
$(list_docs "$dir")
EOF
  fi
  printf '%s\n' "$END"
}

cmd_index() {
  local mode="--write" root=""
  for a in "$@"; do
    case "$a" in --write|--check) mode="$a" ;; *) root="$a" ;; esac
  done
  root="${root:-$ROOT_DEFAULT}"
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }

  local rc=0 dir idx tmp blockfile
  blockfile="$(mktemp)"
  # Deepest-first so a parent _index.md can read freshly-written child descriptions in one pass.
  while IFS= read -r dir; do
    idx="$dir/_index.md"
    build_block "$dir" > "$blockfile"
    if [ ! -f "$idx" ]; then
      if [ "$mode" = "--check" ]; then echo "MISSING: $idx"; rc=1; continue; fi
      { printf -- '---\ntitle: %s\ndescription: TODO\n---\n\n# %s\n\n' "$(basename "$dir")" "$(basename "$dir")"; cat "$blockfile"; } > "$idx"
      echo "CREATED: $idx"; continue
    fi
    tmp="$(mktemp)"
    block_rewrite "$idx" "$START" "$END" "$blockfile" > "$tmp"
    if ! has_marker "$idx" "$START"; then
      printf '\n' >> "$tmp"; cat "$blockfile" >> "$tmp"
    fi
    if [ "$mode" = "--check" ]; then
      diff -q "$idx" "$tmp" >/dev/null 2>&1 || { echo "DRIFT: $idx (run: scripts/docs.sh index --write)"; rc=1; }
      rm -f "$tmp"
    else
      write_if_changed "$tmp" "$idx" "UPDATED" || true
    fi
  done <<EOF
$(find "$root" -type d | sort -r)
EOF
  rm -f "$blockfile"
  return $rc
}

cmd_links() {
  local root="${1:-$ROOT_DEFAULT}" found=0 file link target base
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }
  while IFS= read -r file; do
    base="$(dirname "$file")"
    while IFS= read -r link; do
      case "$link" in http://*|https://*|mailto:*|\#*|"") continue ;; esac
      link="${link%%#*}"; link="${link%%\?*}"
      [ -z "$link" ] && continue
      case "$link" in /*) target="$link" ;; *) target="$(normalize_path "$base/$link")" ;; esac
      [ -e "$target" ] || { echo "BROKEN LINK: $file -> $link"; found=1; }
    done <<EOF
$(grep -oE '\]\([^)]+\)' "$file" 2>/dev/null | sed -E 's/^\]\(//; s/\)$//')
EOF
  done <<EOF
$(find "$root" -type f -name '*.md' | sort)
EOF

  # Second pass: frontmatter refs in diagram sources. The markdown pass above already
  # validates the caption links these produce, once per embedding doc; this reports
  # the break at its single point of declaration instead.
  local srcfile key val scheme path label bare
  while IFS= read -r srcfile; do
    [ -n "$srcfile" ] || continue
    while IFS=$'\t' read -r key val; do
      [ -n "$key" ] || continue
      IFS=$'\t' read -r scheme path label <<EOF2
$(parse_ref "$val")
EOF2
      [ "$scheme" = "url" ] && continue      # emitted, never resolved, never fetched
      bare="${path%%#*}"
      [ -n "$bare" ] || continue
      target="$(normalize_path "$(dirname "$srcfile")/$bare")"
      [ -e "$target" ] || { echo "BROKEN REF: $srcfile -> $scheme:$path"; found=1; }
    done <<EOF2
$(fm_map "$srcfile" refs)
EOF2
  done <<EOF
$(find "$root" -type f -name '*.diagram.md' | sort)
EOF

  return $found
}

cmd_check() {
  local root="${1:-$ROOT_DEFAULT}" rc=0
  # Resolve the root once here, so a missing root is reported once rather than by
  # each sub-command in turn.
  [ -d "$root" ] || { echo "No such root: $root" >&2; return 1; }
  cmd_index --check "$root" || rc=1
  cmd_diagram_index --check "$root" || rc=1
  cmd_diagram_check "$root" || rc=1
  cmd_links "$root" || rc=1
  [ "$rc" -eq 0 ] && echo "docs check: OK"
  return $rc
}

cmd_diagram() {
  local op="${1:-index}"; shift || true
  case "$op" in
    index)  cmd_diagram_index "$@" ;;
    check)  cmd_diagram_check "$@" ;;
    bless)  cmd_diagram_bless "$@" ;;
    render) cmd_diagram_render "$@" ;;
    *) echo "Usage: docs.sh diagram {index [--write|--check]|check|bless <name>|render} [root]" >&2; return 2 ;;
  esac
}

sub="${1:-check}"; shift || true
case "$sub" in
  index)   cmd_index "$@" ;;
  links)   cmd_links "$@" ;;
  diagram) cmd_diagram "$@" ;;
  check)   cmd_check "$@" ;;
  *) echo "Usage: docs.sh {index [--write|--check]|links|diagram index [--write|--check]|check} [root]" >&2; exit 2 ;;
esac
