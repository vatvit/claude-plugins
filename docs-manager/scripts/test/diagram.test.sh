#!/usr/bin/env bash
# Tests for docs-manager: the existing index/links behaviour and the diagram feature.
#
# Dual-target on purpose. Run on the HOST (macOS: bash 3.2 + BSD userland) to catch
# `declare -A`, globstar and GNU-only flags; run in a container (bash 5 + GNU
# coreutils) to catch BSD-only constructs. Either target alone passes green while
# the other is broken.
#
#   bash docs-manager/scripts/test/diagram.test.sh
#   docker run --rm -v "$PWD":/w -w /w bash:5 bash docs-manager/scripts/test/diagram.test.sh
set -uo pipefail

DOCS="$(cd "$(dirname "$0")/.." && pwd)/docs.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
pass=0 fail=0

check() { # check <name> <expected> <actual>
    if [ "$2" = "$3" ]; then pass=$((pass+1)); echo "  ok   $1"
    else fail=$((fail+1)); echo "  FAIL $1"; echo "         expected: [$2]"; echo "         actual:   [$3]"; fi
}
check_rc() { # check_rc <name> <expected-rc> <actual-rc>
    check "$1" "$2" "$3"
}

# fresh <dir> — an empty docs root under $TMP
fresh() { rm -rf "$TMP/$1"; mkdir -p "$TMP/$1"; echo "$TMP/$1"; }

doc() { # doc <path> <body...>
    mkdir -p "$(dirname "$1")"
    { printf -- '---\ntitle: t\ndescription: d\n---\n\n'; cat; } > "$1"
}
src() { # src <path> <fence-body...>
    mkdir -p "$(dirname "$1")"
    { printf -- '---\ntitle: s\n---\n\n'; cat; } > "$1"
}

echo "== existing behaviour (guards the lib.sh extraction) =="

