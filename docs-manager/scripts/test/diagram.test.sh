# srcwatch <path> <watch-list> — a source with watch: and one fence
srcwatch() {
    local p="$1"; shift
    mkdir -p "$(dirname "$p")"
    { printf -- '---\ntitle: s\nwatch: [%s]\n---\n\n```mermaid\nflowchart LR\n  a --> b\n```\n' "$1"; } > "$p"
}
stale_count() { bash "$DOCS" diagram check "$1" 2>/dev/null | grep -c '^STALE:'; }

