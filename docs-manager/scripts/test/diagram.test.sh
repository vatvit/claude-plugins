#!/bin/bash
# Tests for docs-manager: the existing index/links behaviour and the diagram feature.
#
# Dual-target on purpose. Run on the HOST (macOS: bash 3.2 + BSD userland) to catch
# `declare -A`, globstar and GNU-only flags; run in a container (bash 5 + GNU
# coreutils) to catch BSD-only constructs. Either target alone passes green while
# the other is broken.
#
#   bash docs-manager/scripts/test/diagram.test.sh
#   docker run --rm -v "$PWD":/w -w /w bash:5 bash docs-manager/scripts/test/diagram.test.sh
set -uo pipefail

DOCS="$(cd "$(dirname "$0")/.." && pwd)/docs.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
pass=0 fail=0

check() { # check <name> <expected> <actual>
    if [ "$2" = "$3" ]; then pass=$((pass+1)); echo "  ok   $1"
    else fail=$((fail+1)); echo "  FAIL $1"; echo "         expected: [$2]"; echo "         actual:   [$3]"; fi
}
check_rc() { # check_rc <name> <expected-rc> <actual-rc>
    check "$1" "$2" "$3"
}

# fresh <dir> — an empty docs root under $TMP
fresh() { rm -rf "$TMP/$1"; mkdir -p "$TMP/$1"; echo "$TMP/$1"; }

doc() { # doc <path> <body...>
    mkdir -p "$(dirname "$1")"
    { printf -- '---\ntitle: t\ndescription: d\n---\n\n'; cat; } > "$1"
}
src() { # src <path> <fence-body...>
    mkdir -p "$(dirname "$1")"
    { printf -- '---\ntitle: s\n---\n\n'; cat; } > "$1"
}

echo "== existing behaviour (guards the lib.sh extraction) =="

# --- 26: index/links on a diagram-free tree behave as before ----------------
R=$(fresh r26)
doc "$R/a.md" <<'EOF'
See [b](b.md).
EOF
doc "$R/b.md" <<'EOF'
Hi.
EOF
bash "$DOCS" index --write "$R" >/dev/null 2>&1
check "26a _index.md created" "yes" "$([ -f "$R/_index.md" ] && echo yes || echo no)"
check "26b lists both docs" "2" "$(grep -c '^- \[`[ab].md`\]' "$R/_index.md")"
before=$(cat "$R/_index.md")
bash "$DOCS" index --write "$R" >/dev/null 2>&1
check "26c idempotent" "same" "$([ "$before" = "$(cat "$R/_index.md")" ] && echo same || echo changed)"
bash "$DOCS" links "$R" >/dev/null 2>&1; check_rc "26d links clean" "0" "$?"
doc "$R/c.md" <<'EOF'
Broken [x](nope.md).
EOF
bash "$DOCS" links "$R" >/dev/null 2>&1; check_rc "26e links detects break" "1" "$?"

echo "== error paths =="

# --- 20: no fenced block ---------------------------------------------------
R=$(fresh r20)
doc "$R/d.md" <<'EOF'
<!-- DIAGRAM:x.diagram.md -->
EOF
src "$R/x.diagram.md" <<'EOF'
nothing here
EOF
out=$(bash "$DOCS" diagram index --write "$R" 2>&1); rc=$?
check_rc "20a non-zero" "1" "$rc"
check "20b names the file" "yes" "$(echo "$out" | grep -q 'x.diagram.md' && echo yes || echo no)"

# --- 21: two fenced blocks -------------------------------------------------
R=$(fresh r21)
doc "$R/d.md" <<'EOF'
<!-- DIAGRAM:x.diagram.md -->
EOF
src "$R/x.diagram.md" <<'EOF'
```mermaid
a --> b
```

```mermaid
c --> d
```
EOF
out=$(bash "$DOCS" diagram index --write "$R" 2>&1); rc=$?
check_rc "21a non-zero" "1" "$rc"
check "21b reports 2 blocks" "yes" "$(echo "$out" | grep -q '2 fenced blocks' && echo yes || echo no)"

# --- 22: no language tag ---------------------------------------------------
R=$(fresh r22)
doc "$R/d.md" <<'EOF'
<!-- DIAGRAM:x.diagram.md -->
EOF
src "$R/x.diagram.md" <<'EOF'
```
a --> b
```
EOF
out=$(bash "$DOCS" diagram index --write "$R" 2>&1); rc=$?
check_rc "22a non-zero" "1" "$rc"
check "22b mentions language tag" "yes" "$(echo "$out" | grep -q 'language tag' && echo yes || echo no)"

# --- 24: marker names a missing source, existing block untouched -----------
R=$(fresh r24)
doc "$R/d.md" <<'EOF'
<!-- DIAGRAM:gone.diagram.md -->
<!-- AUTO-DIAGRAM:START — generated by scripts/docs.sh; edit the .diagram.md source, not this block -->
PRESERVE ME
<!-- AUTO-DIAGRAM:END -->
EOF
out=$(bash "$DOCS" diagram index --write "$R" 2>&1); rc=$?
check_rc "24a non-zero" "1" "$rc"
check "24b reports missing source" "yes" "$(echo "$out" | grep -q 'MISSING SOURCE' && echo yes || echo no)"
check "24c existing block untouched" "yes" "$(grep -q 'PRESERVE ME' "$R/d.md" && echo yes || echo no)"

echo "== generation =="

# --- 1/2: block appears; prose outside markers preserved -------------------
R=$(fresh r1)
doc "$R/d.md" <<'EOF'
INTRO PROSE

<!-- DIAGRAM:x.diagram.md -->

TRAILING PROSE
EOF
src "$R/x.diagram.md" <<'EOF'
```mermaid
flowchart LR
  a --> b
```
EOF
bash "$DOCS" diagram index --write "$R" >/dev/null 2>&1
check "1a fence copied in" "yes" "$(grep -q 'flowchart LR' "$R/d.md" && echo yes || echo no)"
check "1b tag preserved" "yes" "$(grep -q '^```mermaid$' "$R/d.md" && echo yes || echo no)"
check "1c markers present" "1" "$(grep -c 'AUTO-DIAGRAM:START' "$R/d.md")"
check "2a intro preserved" "yes" "$(grep -q 'INTRO PROSE' "$R/d.md" && echo yes || echo no)"
check "2b trailing preserved" "yes" "$(grep -q 'TRAILING PROSE' "$R/d.md" && echo yes || echo no)"

# --- 3: idempotent ---------------------------------------------------------
before=$(cat "$R/d.md")
bash "$DOCS" diagram index --write "$R" >/dev/null 2>&1
check "3 idempotent" "same" "$([ "$before" = "$(cat "$R/d.md")" ] && echo same || echo changed)"

# --- 4: --check on drift ---------------------------------------------------
src "$R/x.diagram.md" <<'EOF'
```mermaid
flowchart LR
  a --> CHANGED
```
EOF
snapshot=$(cat "$R/d.md")
bash "$DOCS" diagram index --check "$R" >/dev/null 2>&1; rc=$?
check_rc "4a --check non-zero on drift" "1" "$rc"
check "4b --check wrote nothing" "same" "$([ "$snapshot" = "$(cat "$R/d.md")" ] && echo same || echo changed)"
bash "$DOCS" diagram index --write "$R" >/dev/null 2>&1
bash "$DOCS" diagram index --check "$R" >/dev/null 2>&1; rc=$?
check_rc "4c --check clean after write" "0" "$rc"

# --- 5: language-agnostic --------------------------------------------------
R=$(fresh r5)
doc "$R/d.md" <<'EOF'
<!-- DIAGRAM:x.diagram.md -->
EOF
src "$R/x.diagram.md" <<'EOF'
```d2
a -> b
```
EOF
bash "$DOCS" diagram index --write "$R" >/dev/null 2>&1; rc=$?
check_rc "5a d2 fence accepted" "0" "$rc"
check "5b d2 tag preserved" "yes" "$(grep -q '^```d2$' "$R/d.md" && echo yes || echo no)"

# --- 7: two embeds at different depths -------------------------------------
R=$(fresh r7)
src "$R/x.diagram.md" <<'EOF'
```mermaid
a --> b
```
EOF
doc "$R/top.md" <<'EOF'
<!-- DIAGRAM:x.diagram.md -->
EOF
doc "$R/deep/nested.md" <<'EOF'
<!-- DIAGRAM:../x.diagram.md -->
EOF
bash "$DOCS" diagram index --write "$R" >/dev/null 2>&1
check "7a top embed generated" "yes" "$(grep -q 'a --> b' "$R/top.md" && echo yes || echo no)"
check "7b nested embed generated" "yes" "$(grep -q 'a --> b' "$R/deep/nested.md" && echo yes || echo no)"

# --- 25: diagram sources are not documents ---------------------------------
R=$(fresh r25)
doc "$R/real.md" <<'EOF'
Hi.
EOF
src "$R/x.diagram.md" <<'EOF'
```mermaid
a --> b
```
EOF
bash "$DOCS" index --write "$R" >/dev/null 2>&1
check "25a real doc listed" "yes" "$(grep -q 'real.md' "$R/_index.md" && echo yes || echo no)"
check "25b diagram source not listed" "no" "$(grep -q 'x.diagram.md' "$R/_index.md" && echo yes || echo no)"

echo
echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
