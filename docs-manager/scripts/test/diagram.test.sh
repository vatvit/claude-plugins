# srcrefs <path> <refs-block> — a source with a refs: map and one fence
srcrefs() {
    local p="$1"; shift
    mkdir -p "$(dirname "$p")"
    { printf -- '---\ntitle: s\nrefs:\n'; cat
      printf -- '---\n\n```mermaid\nflowchart LR\n  a --> b\n```\n'; } > "$p"
}

# --- 6a/6b/6c: schemes, labels, key fallback --------------------------------
R=$(fresh r6)
mkdir -p "$R/code"
: > "$R/code/gateway.ts"
: > "$R/glossary.md"
